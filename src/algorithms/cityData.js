// 转换为对象格式，方便查找
const CITY_MAP = {}
const CITY_LIST = CITY_DATA.map(([name, province, lon, lat]) => {
  const city = { name, province, lon, lat, label: `${name}（${province}）` }
  CITY_MAP[name] = city
  return city
})

/**
 * 根据城市名查找经纬度
 * @param {string} cityName - 城市名（如"郑州"、"成都市"）
 * @returns {{ name: string, province: string, lon: number, lat: number } | null}
 */
export function findCity(cityName) {
  if (!cityName) return null
  // 去掉"市"、"地区"、"自治州"等后缀再查找
  const cleanName = cityName.replace(/[市地区自治州盟县区]$/g, '')
  
  // 精确匹配
  if (CITY_MAP[cleanName]) return CITY_MAP[cleanName]
  if (CITY_MAP[cityName]) return CITY_MAP[cityName]
  
  // 模糊匹配
  return CITY_LIST.find(c => c.name.includes(cleanName) || cleanName.includes(c.name)) || null
}

/**
 * 搜索城市（用于下拉选择）
 * @param {string} keyword - 搜索关键词
 * @param {number} limit - 返回数量上限
 * @returns {Array<{ name: string, province: string, lon: number, lat: number, label: string }>}
 */
export function searchCity(keyword, limit = 10) {
  if (!keyword || !keyword.trim()) return []
  const kw = keyword.trim()
  
  const results = CITY_LIST.filter(c => 
    c.name.includes(kw) || 
    c.province.includes(kw) || 
    c.label.includes(kw)
  )
  
  // 精确匹配排前面
  results.sort((a, b) => {
    const aExact = a.name === kw ? 0 : 1
    const bExact = b.name === kw ? 0 : 1
    return aExact - bExact
  })
  
  return results.slice(0, limit)
}

/**
 * 获取所有城市列表
 * @returns {Array}
 */
export function getAllCities() {
  return CITY_LIST
}

